"""Snapshot -> JSON Schema (Draft 2020-12) for editor completion (yaml-language-server)."""
from __future__ import annotations

from typing import Any

from .snapshot import load_snapshot

DRAFT = "https://json-schema.org/draft/2020-12/schema"
_ENV_REF = {"type": "string", "pattern": "^os\\.environ/"}


def _prop(entry: dict[str, Any]) -> dict[str, Any]:
    types = [t for t in entry.get("type", ["any"])]
    if "any" in types:
        return {}
    main: dict[str, Any] = {"type": types if len(types) > 1 else types[0]}
    if "enum" in entry:
        main["enum"] = entry["enum"]
    if "string" in types:
        return main
    # any non-string value may be written as os.environ/NAME
    return {"anyOf": [main, _ENV_REF]}


def _section(keys: dict[str, Any], extra: bool) -> dict[str, Any]:
    props = {name: _prop(entry) for name, entry in sorted(keys.items())}
    return {"type": "object", "properties": props, "additionalProperties": extra}


def export_schema(litellm_version: str | None = None) -> dict[str, Any]:
    """Build the JSON Schema for the built-in snapshot."""
    snap = load_snapshot(*([litellm_version] if litellm_version else []))
    version = snap["meta"]["litellm_version"]
    fallback_keys = snap["rules"]["fallback_keys"]

    router = _section(snap["router_settings"], False)
    general = _section(snap["general_settings"], False)
    lsettings = _section(snap["litellm_settings"], True)
    for key in fallback_keys:
        lsettings["properties"][key] = {"type": "array"}

    params = _section(snap["litellm_params"], True)
    params["required"] = ["model"]
    model_entry = {
        "type": "object",
        "properties": {
            "model_name": {"type": "string"},
            "litellm_params": params,
            "model_info": {"type": "object"},
        },
        "required": ["model_name", "litellm_params"],
    }
    top = {name: {} for name in snap["top_level"]}
    top.update(
        {
            "model_list": {"type": "array", "items": model_entry},
            "router_settings": router,
            "general_settings": general,
            "litellm_settings": lsettings,
            "environment_variables": {"type": "object"},
        }
    )
    return {
        "$schema": DRAFT,
        "$id": f"urn:litellm-lint:schema:litellm-{version}",
        "title": f"LiteLLM proxy config.yaml (keys from litellm {version}; unofficial)",
        "description": (
            f"Generated by litellm-lint from the litellm {version} snapshot ({snap['meta']['generated_at']}). "
            "Reference checks (fallbacks, aliases, env vars) need 'litellm-lint check'."
        ),
        "type": "object",
        "properties": top,
        "additionalProperties": True,
    }
